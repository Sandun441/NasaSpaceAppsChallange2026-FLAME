"""NASA FLAME Gemini-controlled research dispatcher.

Register with app.include_router(create_ai_execution_router(prompt_service)).
Gemini selects a tool. Existing specialist service computes real results.
No deterministic narrative fallback is returned on Gemini failures.
"""
from __future__ import annotations

import json
import logging
import re
from typing import Any

from fastapi import APIRouter
from pydantic import BaseModel, Field

from prompt_system.models import PromptResearchRequest
from rag.gemini_provider import GeminiProvider

logger = logging.getLogger('flame.ai_execution')
WORKSPACES = {'visualization', 'comparison', 'modeling', 'gap_detection', 'equipment', 'earth_applications'}


class AIExecutionRequest(BaseModel):
    question: str = Field(min_length=1, max_length=1500)
    conversation_history: list[dict[str, Any]] = Field(default_factory=list)
    context_filters: dict[str, Any] = Field(default_factory=dict)


def _json_from_gemini(raw: str) -> dict[str, Any]:
    raw = (raw or '').strip()
    match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', raw, flags=re.S | re.I)
    if match:
        raw = match.group(1)
    else:
        start, end = raw.find('{'), raw.rfind('}')
        if start >= 0 and end > start:
            raw = raw[start:end + 1]
    result = json.loads(raw)
    if not isinstance(result, dict):
        raise ValueError('Expected JSON object')
    return result


def _gemini_call(provider: GeminiProvider, system: str, user: str) -> str:
    result = provider.generate(system_instruction=system, user_prompt=user)
    if not result.get('success'):
        raise RuntimeError(str(result.get('error') or 'Gemini request failed'))
    return result.get('raw_text', '')


def _unavailable(exc: Exception, question: str) -> dict[str, Any]:
    logger.warning('FLAME AI request failed: %s', exc)
    return {
        'question': question, 'answer': None, 'status': 'ai_unavailable',
        'error_code': 'GEMINI_API_ERROR', 'retryable': True,
        'error_message': 'Gemini was unable to complete this request.',
        'evidence_citations': [], 'suggested_actions': [],
        'llm_provider_status': {'provider': 'google-gemini', 'status': 'error', 'reason': str(exc)},
    }


def create_ai_execution_router(prompt_service, provider: GeminiProvider | None = None) -> APIRouter:
    """Use the already-initialized PromptResearchService from api/main.py."""
    llm = provider or GeminiProvider()
    router = APIRouter(prefix='/api/ai', tags=['Gemini research execution'])

    @router.post('/execute')
    def execute(req: AIExecutionRequest):
        question = req.question.strip()
        if not llm.is_configured:
            return _unavailable(RuntimeError('GEMINI_API_KEY not configured'), question)
        history = [
            {'role': str(t.get('role', 'user'))[:20], 'content': str(t.get('content', ''))[:1200]}
            for t in req.conversation_history[-8:]
        ]
        try:
            decision_raw = _gemini_call(
                llm,
                'You route NASA FLAME research queries. Return ONLY JSON with keys: '
                '"workspace" (one of conversation, visualization, comparison, modeling, gap_detection, equipment, earth_applications), '
                '"resolved_question" (self-contained query resolving pronouns from history), '
                '"needs_clarification" (boolean), "clarification" (string). '
                'Choose conversation for greetings, identity questions, unrelated/general questions or educational explanations '
                'that do not request execution of a research tool. Choose a specialist only when the user requests '
                'actual visualization, experimental comparison, modeling dataset preparation, gap analysis, '
                'fire-safety equipment research, or terrestrial applications. '
                'Do not invent experiment identifiers, measurement values, or missing context. '
                'For ambiguous execution requests set needs_clarification=true.',
                json.dumps({'history': history, 'latest_question': question}, ensure_ascii=False),
            )
            decision = _json_from_gemini(decision_raw)
            workspace = _apply_routing_safeguard(decision.get('workspace'), question)
            if workspace not in WORKSPACES | {'conversation'}:
                raise ValueError('Gemini returned an unsupported workspace')
            if decision.get('needs_clarification'):
                clarification = str(decision.get('clarification') or 'Which experiment or dataset should I use?')
                # The question is generated by Gemini, not a fixed scientific essay.
                return {'status': 'needs_clarification', 'answer': clarification,
                        'question': question, 'evidence_citations': [], 'suggested_actions': []}
            resolved = str(decision.get('resolved_question') or question).strip()[:1500]
            if workspace == 'conversation':
                answer = _gemini_call(
                    llm,
                    'You are NASA FLAME Research Intelligence. Answer naturally and accurately. '
                    'For general conversation, do not pretend to have retrieved NASA records. '
                    'If the user asks you to execute a data tool, clarify that tools require an explicit research operation. '
                    'Return a valid JSON object containing one answer string.',
                    json.dumps({'history': history, 'question': question}, ensure_ascii=False),
                )
                return {'status': 'gemini_conversation', 'answer': answer, 'question': question,
                        'evidence_citations': [], 'suggested_actions': [],
                        'llm_provider_status': {'is_configured': True, 'provider': 'google-gemini', 'model': llm.model_name, 'status': 'success'}}

            # All calculations, charts and measurements must come from the existing specialist engine.
            research = prompt_service.process_prompt(PromptResearchRequest(
                objective=resolved, workspace=workspace, context_filters=req.context_filters,
                conversation_context=history,
            ))
            result = research.model_dump(mode='json')
            if research.status != 'ok':
                # Do not misrepresent missing/ambiguous data as a completed operation.
                return {'status': 'tool_' + research.status, 'question': question,
                        'answer': research.grounded_answer if research.status == 'ambiguous' else None,
                        'tool_result': result, 'suggested_actions': result.get('suggested_actions', []),
                        'scientific_limitations': result.get('scientific_caveats', []),
                        'evidence_citations': [], 'llm_provider_status': {'provider': 'google-gemini', 'model': llm.model_name}}

            # Never send full high-volume telemetry to Gemini. Actual charts stay in tool_result.
            summary = {
                'workspace': workspace,
                'verified_findings': result.get('key_findings', [])[:12],
                'limitations': result.get('scientific_caveats', [])[:12],
                'citations': result.get('provenance_citations', [])[:15],
                'chart_titles': [c.get('title') for c in result.get('visualizations', [])],
                'specialist_data_keys': list(result.get('specialist_data', {}).keys()),
                'evidence_sufficiency': result.get('evidence_sufficiency'),
            }
            answer = _gemini_call(
                llm,
                'You are NASA FLAME scientific research assistant. Explain the completed tool result concisely '
                'using ONLY the verified findings and provenance sent to you. Do not invent numeric values, '
                'scientific observations, citations, exports, or conclusions. If the provided evidence is not '
                'sufficient, clearly explain the limitation. Distinguish recording duration from burning duration. '
                'Cite only supplied citation IDs, and never claim commercial adoption without proof. '
                'Charts/data are rendered separately; do not pretend you made a chart yourself. ' 'Return a valid JSON object containing one answer string with concise Markdown prose.',
                json.dumps({'research_question': resolved, 'verified_tool_output': summary}, ensure_ascii=False, default=str),
            )
            return {
                'question': question, 'answer': answer, 'status': 'tool_executed',
                'tool_workspace': workspace, 'tool_result': result,
                'suggested_actions': [],  # Tool already executed: avoid unrelated suggestions.
                'scientific_limitations': result.get('scientific_caveats', []),
                'evidence_citations': [],  # Specialist provenance is in tool_result; not RAG record cards.
                'llm_provider_status': {'is_configured': True, 'provider': 'google-gemini', 'model': llm.model_name, 'status': 'success'},
            }
        except Exception as exc:
            return _unavailable(exc, question)

    return router

def _apply_routing_safeguard(workspace: str, question: str) -> str:
    """Correct clearly identifiable modeling requests."""
    intent = question.lower()

    modeling_terms = (
        "feature completeness",
        "feature extraction",
        "feature selection",
        "data quality",
        "missing values",
        "missing data",
        "training dataset",
        "training data",
        "target variable",
        "groupkfold",
        "data leakage",
        "predictive modeling",
        "machine learning dataset",
    )

    comparison_terms = (
        "compare ",
        "comparison between",
        "versus",
        " vs ",
        "difference between",
    )

    if (
        any(term in intent for term in modeling_terms)
        and not any(term in intent for term in comparison_terms)
    ):
        return "modeling"

    return workspace
