import React from 'react';

export function DataPreviewTable({
  previewData,
  isLoading,
  selectedTargetId,
}) {
  if (isLoading) {
    return (
      <div className="p-12 text-center bg-slate-50 rounded-2xl border border-slate-200 space-y-3">
        <div className="w-6 h-6 border-2 border-orange-500 border-t-transparent rounded-full animate-spin mx-auto" />
        <p className="text-xs text-slate-500 font-mono">
          Loading experimental data preview from NASA records...
        </p>
      </div>
    );
  }

  if (!previewData || !previewData.preview_rows || previewData.preview_rows.length === 0) {
    return (
      <div className="p-8 text-center bg-slate-50 rounded-2xl border border-slate-200 space-y-2">
        <p className="text-xs text-slate-700 font-medium">No Experimental Records Matched Filters</p>
        <p className="text-[11px] text-slate-500 font-mono">
          Try broadening the material filter, adjusting the oxygen/flow range, or toggling complete cases.
        </p>
      </div>
    );
  }

  const columns = previewData.columns || [];
  const rows = previewData.preview_rows || [];
  const totalFiltered = previewData.total_filtered_count || previewData.total_extracted_count || rows.length;
  const completeCases = previewData.complete_case_count;
  const labeledCount = previewData.labeled_count;
  const anomalousCount = previewData.anomalous_count || 0;

  return (
    <div className="bg-white border border-slate-200 rounded-2xl p-4 sm:p-5 shadow-sm space-y-3">
      {/* Table Header Summary */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 pb-2 border-b border-slate-200">
        <div>
          <div className="flex items-center gap-2 flex-wrap">
            <h3 className="text-xs font-semibold text-slate-900 uppercase tracking-wider">
              Experimental Data Preview
            </h3>
            <span className="text-orange-700 font-mono text-[11px] bg-orange-50 px-2 py-0.5 rounded border border-orange-200">
              Showing {rows.length} preview rows of {totalFiltered} filtered records
            </span>
          </div>
          <p className="text-[11px] text-slate-500 mt-1">
            Exact empirical records generated by backend extraction. Exported CSV guarantees 1:1 match with preview.
          </p>
        </div>

        {/* Population & Role Indicators */}
        <div className="flex flex-wrap items-center gap-2 text-[10px] font-mono text-slate-500">
          {completeCases !== undefined && (
            <span className="bg-emerald-50 px-2 py-0.5 rounded border border-emerald-200 text-emerald-800">
              ✓ {completeCases} complete cases
            </span>
          )}
          {selectedTargetId && labeledCount !== undefined && (
            <span className="bg-orange-50 px-2 py-0.5 rounded border border-orange-200 text-orange-800">
              🎯 {labeledCount} labeled
            </span>
          )}
          {anomalousCount > 0 && (
            <span className="bg-amber-50 px-2 py-0.5 rounded border border-amber-200 text-amber-800">
              ⚠️ {anomalousCount} flagged source anomalies
            </span>
          )}
          <span className="flex items-center gap-1 ml-1 pl-2 border-l border-slate-200">
            <span className="w-2 h-2 rounded bg-orange-500" /> Target
          </span>
          <span className="flex items-center gap-1">
            <span className="w-2 h-2 rounded bg-slate-400" /> Input
          </span>
          <span className="flex items-center gap-1">
            <span className="w-2 h-2 rounded bg-amber-500" /> Group ID
          </span>
        </div>
      </div>

      {/* Responsive Table Container */}
      <div className="overflow-x-auto border border-slate-200 rounded-xl bg-white max-h-[420px] overflow-y-auto">
        <table className="w-full text-left border-collapse text-xs">
          <thead className="sticky top-0 bg-slate-50 backdrop-blur-sm z-10 border-b border-slate-200 shadow-sm">
            <tr>
              <th className="px-3 py-2.5 text-[10px] font-mono text-slate-500 uppercase tracking-wider w-10">
                #
              </th>
              {columns.map((col) => {
                const isTarget = col.id === selectedTargetId || col.role === 'target';
                const isGroup = col.role === 'group_identifier';
                const isFlag = col.id === 'data_quality_flags';

                return (
                  <th
                    key={col.id}
                    className={`px-3 py-2.5 text-[11px] font-medium tracking-tight whitespace-nowrap ${
                      isTarget
                        ? 'text-orange-900 bg-orange-50 border-b-2 border-orange-500'
                        : isGroup
                        ? 'text-amber-900 bg-amber-50/70'
                        : isFlag
                        ? 'text-amber-800 bg-amber-50/50'
                        : 'text-slate-700'
                    }`}
                  >
                    <div className="flex items-center gap-1.5">
                      <span>{col.label}</span>
                      <span className="text-[10px] font-mono text-slate-400">
                        [{col.unit}]
                      </span>
                    </div>
                    <div className="text-[9px] font-mono text-slate-400 font-normal">
                      {col.id}
                    </div>
                  </th>
                );
              })}
            </tr>
          </thead>

          <tbody className="divide-y divide-slate-100 font-sans">
            {rows.map((row, rowIdx) => {
              const hasAnomaly = Boolean(row.data_quality_flags);

              return (
                <tr
                  key={rowIdx}
                  className={`transition-colors group ${
                    hasAnomaly
                      ? 'bg-amber-50/40 hover:bg-amber-50/80'
                      : 'hover:bg-slate-50/80'
                  }`}
                >
                  <td className="px-3 py-2 text-[10px] font-mono text-slate-400">
                    <span className="flex items-center gap-1">
                      {rowIdx + 1}
                      {hasAnomaly && (
                        <span title={row.data_quality_flags} className="text-amber-600 cursor-help">
                          ⚠️
                        </span>
                      )}
                    </span>
                  </td>
                  {columns.map((col) => {
                    const val = row[col.id];
                    const isTarget = col.id === selectedTargetId || col.role === 'target';
                    const isGroup = col.role === 'group_identifier';
                    const isFlag = col.id === 'data_quality_flags';

                    let displayVal = '—';
                    if (val !== null && val !== undefined) {
                      if (typeof val === 'number') {
                        displayVal = Number.isInteger(val) ? val.toString() : val.toFixed(3);
                      } else {
                        displayVal = String(val);
                      }
                    }

                    return (
                      <td
                        key={col.id}
                        className={`px-3 py-2 font-mono whitespace-nowrap ${
                          isTarget
                            ? 'text-orange-950 font-semibold bg-orange-50/30'
                            : isGroup
                            ? 'text-amber-950 font-semibold bg-amber-50/20'
                            : isFlag && val
                            ? 'text-amber-800 text-[10px]'
                            : val === null || val === undefined
                            ? 'text-slate-400 italic'
                            : 'text-slate-700'
                        }`}
                      >
                        {displayVal}
                      </td>
                    );
                  })}
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}
